"""Deterministic codegen: a :class:`Storyboard` -> Manim ``VoiceoverScene`` source.

The LLM never writes Manim; this template does, from the typed IR. The generated
scene opens with a title card, narrates each beat with ``manim-voiceover``
(audio-led timing), draws a ``plot`` canvas via ``Axes``, overlays a cited
``code_callout`` (built through the version-isolated ``code_compat`` wrapper), and
highlights regions in sync with narration. Layout is a single centered ``content``
VGroup so the composition stays balanced. All authored strings are embedded with
``repr()`` so quotes/newlines cannot break or inject into the generated module.
Plot curve functions are validated through :mod:`plot_expr` before being embedded
as lambdas.
"""

from dataclasses import dataclass

from explainer.storyboard.model import display_line_count

from .plot_expr import PlotExprError, is_piecewise, normalize_curve
from explainer.codegen.common import (
    INDENT,
    LABEL_FONT,
    MUTED_COLOR,
    TEXT_COLOR,
    _s,
    badge_lines,
    cite_basename,
)

# Max seconds for visual plays under a voiceover block. Remainder is wait so
# speech length is preserved without stretching Create/FadeIn across full VO
# (which made Write/Create mid-frames linger for seconds on the public showcase).
VOICEOVER_VISUAL_CAP_S = 0.75

# Straight segments across the x range for a piecewise curve: short enough to read
# as a smooth line, and a bend between two samples is cut by at most 1/400 of the axis.
PIECEWISE_SAMPLES = 400

# Height of the x tick-number row (label buff + 16pt digits). A numbered x axis is
# shortened by it, so the composed beat keeps the frame margins of an unnumbered one.
X_NUMBER_ROW = 0.3


@dataclass
class RevealStep:
    narration: str  # "" => silent
    plays: list  # list of play-expression strings
    run_time: str = "1.0"  # used only for silent steps; voiced steps use the cap + wait
    post_wait: float = 0.0


_HEADER = '''"""Auto-generated by the Explainer Engine. Do not edit by hand."""

from math import exp, log  # noqa: F401  (available to embedded plot lambdas)

from manim import *  # noqa: F401,F403
from manim_voiceover import VoiceoverScene

from explainer.codegen.code_compat import build_code, code_line  # noqa: F401
from explainer.codegen.tts_compat import build_speech_service
'''


class CodegenError(Exception):
    """Raised when a storyboard cannot be turned into a valid Manim scene."""


def generate_scene(storyboard, scene_name="ExplainerVideo", lang="en"):
    """Return Python source for a Manim ``VoiceoverScene`` rendering ``storyboard``."""
    body = []
    if storyboard.theme.background:
        body.append(f"{INDENT}self.camera.background_color = {_s(storyboard.theme.background)}")
    body.append(f"{INDENT}self.set_speech_service(build_speech_service(lang={_s(lang)}))")
    body.extend(_emit_title_card(storyboard))
    for i, beat in enumerate(storyboard.beats):
        body.append(f"{INDENT}# --- beat: {beat.id} ---")
        body.extend(_emit_beat(beat, storyboard))
        if i != len(storyboard.beats) - 1:
            body.append(f"{INDENT}_others = [m for m in self.mobjects if m is not title_strip]")
            body.append(f"{INDENT}if _others:")
            body.append(f"{INDENT}    self.play(*[FadeOut(m) for m in _others], run_time=0.5)")
    lines = [
        _HEADER,
        "",
        f"class {scene_name}(VoiceoverScene):",
        "    def construct(self):",
        *body,
    ]
    return "\n".join(lines) + "\n"


def _emit_title_card(storyboard):
    """Opening title card (title + subtitle), then a small persistent top strip."""
    title = storyboard.title
    subtitle = storyboard.subtitle
    strip_title = title.replace(" ", "  ")
    out = [
        f"{INDENT}title = Text({_s(title)}, font={_s(LABEL_FONT)}, font_size=46, "
        f"color={_s(TEXT_COLOR)}, disable_ligatures=True)",
    ]
    if subtitle:
        out += [
            f"{INDENT}subtitle = Text({_s(subtitle)}, font={_s(LABEL_FONT)}, font_size=24, "
            f"color={_s(MUTED_COLOR)}, disable_ligatures=True)",
            f"{INDENT}card = VGroup(title, subtitle).arrange(DOWN, buff=0.35).move_to(ORIGIN)",
            f"{INDENT}self.play(FadeIn(title, shift=UP * 0.2), run_time=0.7)",
            f"{INDENT}self.play(FadeIn(subtitle), run_time=0.5)",
            f"{INDENT}self.wait(0.8)",
            f"{INDENT}self.play(FadeOut(card), run_time=0.6)",
        ]
    else:
        out += [
            f"{INDENT}self.play(FadeIn(title, shift=UP * 0.2), run_time=0.7)",
            f"{INDENT}self.wait(0.8)",
            f"{INDENT}self.play(FadeOut(title), run_time=0.6)",
        ]
    out += [
        f"{INDENT}title_strip = Text({_s(strip_title)}, font={_s(LABEL_FONT)}, font_size=18, "
        f"color={_s(MUTED_COLOR)}, disable_ligatures=True).to_edge(UP, buff=0.3)",
        f"{INDENT}self.add(title_strip)",
    ]
    return out


def _accent_color(accent, theme, default):
    if accent == "confirmed":
        return theme.accent_confirmed
    if accent == "contradicted":
        return theme.accent_contradicted
    return default


def _curve_color(curve, theme):
    if curve.get("accent"):
        return _accent_color(curve.get("accent"), theme, "#9CDCFE")
    if curve.get("style") == "faint":
        return "#888888"
    return "#9CDCFE"


def _emit_tick_numbers(axis, spec, lo, step, other_min):
    """Label the axis's five ticks (``lo + k * step``) when its spec says ``numbers: true``.

    Sans ``Text`` like every other plot label (Manim's own numbers need LaTeX), added
    through ``add_labels`` so they become part of the axis: the axis title, placed
    ``next_to`` the axis afterwards, then clears them. The 0 label is dropped when the
    other axis runs on past this one (``other_min < 0``): its line would strike it.
    """
    numbers = spec.get("numbers", False)
    if not isinstance(numbers, bool):
        raise CodegenError(f"plot {axis}.numbers must be true or false, got {numbers!r}")
    if not numbers:
        return []
    values = (round(lo + k * step, 9) + 0.0 for k in range(5))  # + 0.0: no -0.0
    ticks = ", ".join(
        # Positional, never scientific: '1500000' and '25000.25', not '1.5e+06'.
        f"({v!r}, {_s(f'{v:.9f}'.rstrip('0').rstrip('.'))})"
        for v in values
        if v != 0 or other_min >= 0
    )
    return [
        f"{INDENT}axes.{axis}_axis.add_labels({{v: Text(s, font={_s(LABEL_FONT)}, font_size=16, "
        f"color={_s(MUTED_COLOR)}, disable_ligatures=True) for v, s in ({ticks})}}, font_size=16)"
    ]


def _emit_plot(spec, theme):
    """Emit Axes + sans labels + curves + annotations, grouped as ``plot_group``.

    Returns ``(lines, curves, anns, legend)``; each ann is a ``(var, region)`` pair,
    ``region`` being the authored 1-based region number or ``None``. Curves and
    annotations are constructed but not yet animated; :func:`_emit_beat` decides the
    reveal choreography.
    """
    x = spec.get("x", {}) or {}
    y = spec.get("y", {}) or {}
    xmin, xmax = x.get("min", 0), x.get("max", 10)
    ymin, ymax = y.get("min", 0), y.get("max", 1)
    xstep = (xmax - xmin) / 4.0 or 1
    ystep = (ymax - ymin) / 4.0 or 1
    x_numbers = _emit_tick_numbers("x", x, xmin, xstep, ymin)
    y_length = 3.25 - X_NUMBER_ROW if x_numbers else 3.25
    lines = [
        f"{INDENT}axes = Axes(x_range=[{xmin}, {xmax}, {xstep}], "
        f"y_range=[{ymin}, {ymax}, {ystep}], x_length=10.0, y_length={y_length!r}, "
        f"axis_config={{'color': {_s(MUTED_COLOR)}, 'include_numbers': False}}, tips=False)",
        *x_numbers,
        *_emit_tick_numbers("y", y, ymin, ystep, xmin),
        f"{INDENT}x_label = Text({_s(x.get('label', ''))}, font={_s(LABEL_FONT)}, font_size=19, "
        f"color={_s(TEXT_COLOR)}, disable_ligatures=True).next_to(axes.x_axis, DOWN, buff=0.22)",
        f"{INDENT}y_label = Text({_s(y.get('label', ''))}, font={_s(LABEL_FONT)}, font_size=19, "
        f"color={_s(TEXT_COLOR)}, disable_ligatures=True).rotate(PI / 2)"
        f".next_to(axes.y_axis, LEFT, buff=0.22)",
        f"{INDENT}axis_labels = VGroup(x_label, y_label)",
    ]
    curves = []
    legend_entries = []  # (color, label) for curves that carry an authored label
    for i, curve in enumerate(spec.get("curves", []) or []):
        fn = str(curve.get("fn", "0"))
        try:
            safe_fn = normalize_curve(fn)
        except PlotExprError as exc:
            raise CodegenError(f"unsafe/invalid curve fn {fn!r}: {exc}") from exc
        var = f"curve{i}"
        color = _curve_color(curve, theme)
        if is_piecewise(safe_fn):
            # Manim smooths a plot through its samples, which rounds every bend of a
            # min/max/abs/% curve. Dense straight segments keep the bends sharp; smooth
            # curves keep the default sampling, so their output is unchanged.
            step = (xmax - xmin) / PIECEWISE_SAMPLES
            sampling = f"x_range=[{xmin}, {xmax}, {step!r}], use_smoothing=False"
        else:
            sampling = f"x_range=[{xmin}, {xmax}]"
        lines.append(
            f"{INDENT}{var} = axes.plot(lambda x: {safe_fn}, {sampling}, "
            f"color={_s(color)}, stroke_width=4)"
        )
        curves.append(var)
        label = str(curve.get("label", "") or "").strip()
        if label:
            legend_entries.append((color, label))
    anns = []
    for i, ann in enumerate(spec.get("annotations", []) or []):
        kind = ann.get("kind")
        if kind != "hline":
            raise CodegenError(f"unsupported annotation kind {kind!r} (v1 supports: hline)")
        try:
            yv = float(ann.get("y", 0))
        except (TypeError, ValueError) as exc:
            raise CodegenError(f"annotation y must be numeric, got {ann.get('y')!r}") from exc
        color = _accent_color(ann.get("accent"), theme, "#888888")
        label_text = f"{yv:g} {ann.get('label', '')}".strip()
        var = f"ann{i}"
        lines += [
            f"{INDENT}{var}_line = DashedLine(axes.c2p({xmin}, {yv}), axes.c2p({xmax}, {yv}), "
            f"color={_s(color)}, stroke_width=2, dash_length=0.08)",
            f"{INDENT}{var}_label = Text({_s(label_text)}, font={_s(LABEL_FONT)}, font_size=16, "
            f"color={_s(color)}, disable_ligatures=True).next_to({var}_line, UP, buff=0.08)"
            f".align_to({var}_line, RIGHT).shift(LEFT * 0.3)",
            f"{INDENT}{var} = VGroup({var}_line, {var}_label)",
        ]
        anns.append((var, ann.get("region")))
    # Legend: one colored swatch + label per labeled curve, anchored top-right inside
    # the axes (decay curves sit low on the right, so that corner stays clear). This is
    # the only thing identifying which curve is which -- color alone is not enough.
    legend = None
    if legend_entries:
        legend = "legend"
        rows = []
        for k, (color, label) in enumerate(legend_entries):
            rv = f"leg{k}"
            lines += [
                f"{INDENT}{rv}_swatch = Line(ORIGIN, RIGHT * 0.45, "
                f"color={_s(color)}, stroke_width=5)",
                f"{INDENT}{rv}_text = Text({_s(label)}, font={_s(LABEL_FONT)}, font_size=16, "
                f"color={_s(color)}, disable_ligatures=True)",
                f"{INDENT}{rv} = VGroup({rv}_swatch, {rv}_text).arrange(RIGHT, buff=0.12)",
            ]
            rows.append(rv)
        lines += [
            f"{INDENT}legend = VGroup({', '.join(rows)})"
            f".arrange(DOWN, aligned_edge=LEFT, buff=0.14)",
            f"{INDENT}legend.align_to(axes, UP).align_to(axes, RIGHT)"
            f".shift(DOWN * 0.15 + LEFT * 0.2)",
        ]

    members = ["axes", "axis_labels"] + curves + [a for a, _ in anns] + ([legend] if legend else [])
    lines.append(f"{INDENT}plot_group = VGroup({', '.join(members)})")
    return lines, curves, anns, legend


def _emit_provenance(callout, source, theme):
    """A compact provenance row rendered under the code block.

    Shows ``<basename>:<line>`` + an amber ``simplified`` tag (the on-screen code is
    a teaching simplification, never claimed verbatim) + a green ``verified @
    <commit>`` badge. So the differentiator -- every on-screen code fact checked
    against real source -- is visible in the video, while honesty about the display
    is explicit; ``explainer verify`` proves the exact source tokens.
    """
    cite_label = cite_basename(callout.cite or "")
    badge = f"verified @ {source.commit}" if source.commit else "verified"
    # Same provenance row the diagram beat renders -- share the one builder so the
    # font/order/spacing can never drift between the code and diagram paths.
    return badge_lines("provenance", cite_label, badge, theme.accent_confirmed)


def _emit_reveal_steps(steps):
    """Emit voiceover/silent blocks for an ordered list of RevealSteps."""
    inner = INDENT + "    "
    out = []
    for step in steps:
        if not step.plays:
            if step.post_wait:
                out.append(f"{INDENT}self.wait({step.post_wait})")
            continue
        if step.narration:
            plays = ", ".join(step.plays)
            out.append(f"{INDENT}with self.voiceover(text={_s(step.narration)}) as tracker:")
            # Cap visual run_time; hold for the rest of the speech so VO length
            # still drives pacing without stretched mid-animation frames.
            out.append(
                f"{inner}self.play({plays}, "
                f"run_time=min({VOICEOVER_VISUAL_CAP_S}, tracker.duration))"
            )
            out.append(
                f"{inner}self.wait(max(0, tracker.duration - "
                f"min({VOICEOVER_VISUAL_CAP_S}, tracker.duration)))"
            )
        else:
            out.append(f"{INDENT}self.play({', '.join(step.plays)}, run_time={step.run_time})")
        if step.post_wait:
            out.append(f"{INDENT}self.wait({step.post_wait})")
    return out


def _emit_beat(beat, storyboard):
    theme = storyboard.theme
    if beat.canvas.kind == "diagram":
        from explainer.codegen.diagram_codegen import emit_diagram

        setup, steps = emit_diagram(beat, storyboard)
        out = list(setup)
        out.extend(_emit_reveal_steps(steps))
        if beat.caption:
            _cap_buff = 0.85 if beat.canvas.diagram.claims else 0.4
            out.append(
                f"{INDENT}caption = Text({_s(beat.caption)}, font={_s(LABEL_FONT)}, "
                f"font_size=16, color={_s(MUTED_COLOR)}, disable_ligatures=True)"
                f".to_edge(DOWN, buff={_cap_buff})"
            )
            out.append(f"{INDENT}self.play(FadeIn(caption), run_time=0.5)")
            out.append(f"{INDENT}self.wait(1.0)")
        out.append(f"{INDENT}self.wait(0.4)")
        return out

    out = []
    curves, anns, legend = [], [], None
    has_plot = beat.canvas.kind == "plot"
    has_code = beat.code_callout is not None
    if not has_plot and not has_code:
        raise CodegenError(
            f"beat {beat.id!r} has no visual content "
            f"(canvas kind {beat.canvas.kind!r}, no code_callout)"
        )

    if has_plot:
        plot_lines, curves, anns, legend = _emit_plot(beat.canvas.spec, theme)
        out.extend(plot_lines)
    if has_code:
        callout = beat.code_callout
        out.append(
            f"{INDENT}code = build_code({_s(callout.display.rstrip())}, "
            f"language={_s(callout.language)}, formatter_style={_s(theme.syntax_style)})"
        )
        if has_plot:
            out.append(f"{INDENT}code.scale_to_fit_width(min(code.width, 10.8))")
        else:
            # code-only canvas: the code is the star -- fill the width (to 11.5
            # units, enlarging short snippets), then cap height so tall code fits.
            out.append(f"{INDENT}code.scale_to_fit_width(11.5)")
            out.append(f"{INDENT}if code.height > 6.0:")
            out.append(f"{INDENT}    code.scale_to_fit_height(6.0)")
        out.extend(_emit_provenance(callout, storyboard.source, theme))
        out.append(
            f"{INDENT}code_block = VGroup(code, provenance)"
            f".arrange(DOWN, buff=0.14, aligned_edge=LEFT)"
        )
    if beat.caption:
        out.append(
            f"{INDENT}caption = Text({_s(beat.caption)}, font={_s(LABEL_FONT)}, font_size=16, "
            f"color={_s(MUTED_COLOR)}, disable_ligatures=True)"
        )
        out.append(f"{INDENT}caption.scale_to_fit_width(min(caption.width, 10.8))")

    # Compose: one centered content stack (no top/bottom pinning -> no dead band).
    if has_plot and has_code:
        members = ["plot_group", "code_block"] + (["caption"] if beat.caption else [])
        out.append(f"{INDENT}content = VGroup({', '.join(members)}).arrange(DOWN, buff=0.5)")
        out.append(f"{INDENT}content.move_to(DOWN * 0.25)")
    elif has_plot:
        out.append(f"{INDENT}plot_group.move_to(DOWN * 0.1)")
    elif has_code:
        # code-only canvas: center the code block (plus caption, if any).
        if beat.caption:
            out.append(f"{INDENT}content = VGroup(code_block, caption).arrange(DOWN, buff=0.5)")
            out.append(f"{INDENT}content.move_to(ORIGIN)")
        else:
            out.append(f"{INDENT}code_block.move_to(ORIGIN)")

    # Reveal axes + code up front (snappy, so narration starts sooner).
    if has_plot:
        out.append(f"{INDENT}self.play(Create(axes), FadeIn(axis_labels), run_time=0.7)")
    if has_code:
        out.append(f"{INDENT}self.play(FadeIn(code_block), run_time=0.4)")

    created = set()

    # Beat narration -> reveal the base (first) curve.
    out.append(f"{INDENT}with self.voiceover(text={_s(beat.narration)}) as tracker:")
    inner = INDENT + "    "
    plays = []
    if curves:
        plays.append(f"Create({curves[0]})")
        created.add(0)
    if plays:
        out.append(f"{inner}self.play({', '.join(plays)}, run_time=tracker.duration)")
    else:
        out.append(f"{inner}self.wait(tracker.duration)")

    # Regions -> per-region voiceover + highlight; fold in the next curve/annotations.
    regions = beat.code_callout.regions if has_code else ()
    for _, region in anns:
        if region is not None and (
            isinstance(region, bool)
            or not isinstance(region, int)
            or not 1 <= region <= len(regions)
        ):
            raise CodegenError(
                f"beat {beat.id!r}: annotation region {region!r} does not name one of "
                f"the beat's {len(regions)} code region(s) (1-based)"
            )
    n_code_lines = display_line_count(beat.code_callout.display) if has_code else 0
    prev_box = None
    for j, region in enumerate(regions):
        region_lines = region.lines or (1,)
        for ln in region_lines:
            if ln < 1 or ln > n_code_lines:
                raise CodegenError(
                    f"beat {beat.id!r}: region line {ln} out of range "
                    f"(callout has {n_code_lines} lines)"
                )
        if len(region_lines) == 1:
            target = f"code_line(code, {region_lines[0]})"
        else:
            target = "VGroup(" + ", ".join(f"code_line(code, {ln})" for ln in region_lines) + ")"
        color = theme.accent_confirmed if region.emphasis == "strong" else "#FFD479"
        box = f"box{j}"
        # A highlight-only region (no narration) plays outside a voiceover block:
        # wrapping it would send an empty string to gTTS at render time. strip()
        # guards programmatically-built Regions; the YAML path is pre-stripped.
        voiced = bool(region.narration.strip())
        if voiced:
            out.append(f"{INDENT}with self.voiceover(text={_s(region.narration)}) as tracker:")
            level, run_time = inner, "tracker.duration"
        else:
            level, run_time = INDENT, "1.0"
        out.append(
            f"{level}{box} = SurroundingRectangle("
            f"{target}, color={_s(color)}, buff=0.025, stroke_width=2)"
        )
        plays = (
            [f"Create({box})"]
            if prev_box is None
            # Cross-fade between region boxes rather than morphing one across lines.
            # ReplacementTransform sweeps the rectangle's edges through the code text
            # mid-tween, which reads as a strikethrough; FadeOut+FadeIn swaps in place.
            else [f"FadeOut({prev_box})", f"FadeIn({box})"]
        )
        nxt = j + 1
        if nxt < len(curves) and nxt not in created:
            plays.append(f"Create({curves[nxt]})")
            created.add(nxt)
        # An annotation tied to a region draws with that region's highlight (and so
        # with its narration, if it has one); an untied one draws with the first region.
        plays.extend(f"Create({a})" for a, r in anns if (r or 1) == j + 1)
        out.append(f"{level}self.play({', '.join(plays)}, run_time={run_time})")
        if not voiced:
            out.append(f"{INDENT}self.wait(0.6)")  # hold the silent highlight briefly
        prev_box = box

    # Any curves not yet revealed (and annotations if there were no regions).
    leftover = [c for k, c in enumerate(curves) if k not in created]
    leftover_anns = [a for a, _ in anns] if not regions else []
    tail = [f"Create({c})" for c in leftover] + [f"Create({a})" for a in leftover_anns]
    if tail:
        out.append(f"{INDENT}self.play({', '.join(tail)}, run_time=1.0)")

    # Reveal the curve legend once the curves are drawn, so labels land on real curves.
    if legend:
        out.append(f"{INDENT}self.play(FadeIn(legend), run_time=0.5)")

    if beat.caption:
        out.append(f"{INDENT}self.play(FadeIn(caption), run_time=0.5)")
        out.append(f"{INDENT}self.wait(1.2)")  # let the closing caption be read

    out.append(f"{INDENT}self.wait(0.4)")
    return out
